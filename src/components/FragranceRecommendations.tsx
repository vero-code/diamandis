export type FragranceRecommendation = {
  name: string
  notes: string
  reason: string
}

type FragranceRecommendationsProps = {
  recommendations: FragranceRecommendation[]
  error: string
}

export function FragranceRecommendations({
  recommendations,
  error,
}: FragranceRecommendationsProps) {
  if (recommendations.length === 0 && !error) return null

  return (
    <section className="panel" aria-live="polite">
      <h2>3. Fragrance Recommendations</h2>
      <p className="note">
        Editorial selections generated by Gemini from the Diamandis catalog using
        your YouCam skin metrics and scent preference. Does not measure or
        guarantee fragrance longevity.
      </p>

      {error && <p role="alert" className="error-text">{error}</p>}

      {recommendations.length > 0 && (
        <div className="metrics">
          {recommendations.map((fragrance) => (
            <article className="metric" key={fragrance.name}>
              <h3>{fragrance.name}</h3>
              <p className="notes">{fragrance.notes}</p>
              <p>{fragrance.reason}</p>
            </article>
          ))}
        </div>
      )}
    </section>
  )
}